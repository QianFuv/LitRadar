// Command sqlc-schema derives sqlc's relational schema inputs from the production migrations.
package main

import (
	"context"
	"database/sql"
	"errors"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/QianFuv/LitRadar/apps/server/internal/sources/scholarly"
	indexstorage "github.com/QianFuv/LitRadar/apps/server/internal/storage/index"
	authmigration "github.com/QianFuv/LitRadar/apps/server/internal/storage/migrations/auth"
	indexmigration "github.com/QianFuv/LitRadar/apps/server/internal/storage/migrations/index"
	telemetrymigration "github.com/QianFuv/LitRadar/apps/server/internal/storage/migrations/telemetry"
	"github.com/QianFuv/LitRadar/apps/server/internal/storage/sqlite"
)

func main() {
	isCheck := flag.Bool("check", false, "check schema inputs without changing files")
	output := flag.String("output", "internal/storage/sqlc/schema", "schema input directory, relative to the server directory")
	flag.Parse()
	if err := run(context.Background(), *output, *isCheck); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(ctx context.Context, output string, isCheck bool) (failure error) {
	directory, err := os.MkdirTemp("", "litradar-sqlc-schema-")
	if err != nil {
		return err
	}
	defer func() { failure = errors.Join(failure, os.RemoveAll(directory)) }()
	for _, name := range []string{"auth", "index", "control", "batch", "telemetry", "workset"} {
		filename := filepath.Join(directory, name+".sqlite")
		if err := migrate(ctx, name, filename); err != nil {
			return fmt.Errorf("migrate %s schema: %w", name, err)
		}
		content, err := schema(ctx, filename)
		if err != nil {
			return fmt.Errorf("read %s schema: %w", name, err)
		}
		target := filepath.Join(output, name+".sql")
		if isCheck {
			previous, err := os.ReadFile(target)
			if err != nil {
				return err
			}
			if string(previous) != content {
				return fmt.Errorf("%s differs from production migrations; run go run ./cmd/sqlc-schema", target)
			}
			continue
		}
		if err := os.MkdirAll(output, 0755); err != nil {
			return err
		}
		if err := os.WriteFile(target, []byte(content), 0644); err != nil {
			return err
		}
	}
	return nil
}

func migrate(ctx context.Context, name, filename string) (failure error) {
	switch name {
	case "auth":
		_, err := authmigration.Migrate(ctx, filename)
		return err
	case "index":
		_, err := indexmigration.Migrate(ctx, filename)
		return err
	case "telemetry":
		return telemetrymigration.Migrate(ctx, filename)
	default:
		database, err := sqlite.OpenMigration(filename)
		if err != nil {
			return err
		}
		defer func() { failure = errors.Join(failure, database.Close()) }()
		connection, err := database.Conn(ctx)
		if err != nil {
			return err
		}
		defer func() { failure = errors.Join(failure, connection.Close()) }()
		if name == "workset" {
			return scholarly.InitCrossrefWorkset(ctx, connection)
		}
		if name == "batch" {
			return indexstorage.InitBatch(ctx, connection)
		}
		return indexstorage.InitControl(ctx, connection)
	}
}

func schema(ctx context.Context, filename string) (content string, failure error) {
	database, err := sqlite.OpenMigration(filename)
	if err != nil {
		return "", err
	}
	defer func() { failure = errors.Join(failure, database.Close()) }()
	return readSchema(ctx, database)
}

func readSchema(ctx context.Context, database *sql.DB) (content string, failure error) {
	rows, err := database.QueryContext(ctx, `SELECT definition.sql FROM sqlite_schema AS definition JOIN pragma_table_list AS tables ON tables.schema='main' AND tables.name=definition.name WHERE definition.type='table' AND tables.type='table' AND definition.name NOT LIKE 'sqlite_%' ORDER BY definition.name`)
	if err != nil {
		return "", err
	}
	defer func() { failure = errors.Join(failure, rows.Close()) }()
	var result strings.Builder
	result.WriteString("-- Code generated by go run ./cmd/sqlc-schema from production migrations. DO NOT EDIT.\n\n")
	for rows.Next() {
		var declaration string
		if err := rows.Scan(&declaration); err != nil {
			return "", err
		}
		result.WriteString(declaration)
		result.WriteString(";\n\n")
	}
	return result.String(), rows.Err()
}
